static void
init_flagimage (
   struct Screen  *scr)
{
   register UWORD   i;
   register UWORD   limit = IMAGESIZE (FLAGIMAGE_WIDTH, FLAGIMAGE_HEIGHT);
   
   if (game_pens[GROUNDPEN] != NOPEN &&
       game_pens[GROUNDPEN] == game_pens[FLAGPEN])
   {
      ReleasePen (scr->ViewPort.ColorMap, game_pens[GROUNDPEN]);
      game_pens[GROUNDPEN] = NOPEN;
   }
   
   for (i = 0; i < limit; ++i)
   {
      switch (flagimage[i])
      {
      case 0:
         flagimage[i] = gui_pens[BACKGROUNDPEN];
         break;
      case 1:
         flagimage[i] = (game_pens[FLAGPEN] == NOPEN) ?
                        gui_pens[FILLPEN] : game_pens[FLAGPEN];
         break;
      case 2:
         flagimage[i] = (game_pens[POLEPEN] == NOPEN) ?
                        gui_pens[SHINEPEN] : game_pens[POLEPEN];
         break;
      case 3:
         flagimage[i] = (game_pens[GROUNDPEN] == NOPEN) ?
                        gui_pens[SHADOWPEN] : game_pens[GROUNDPEN];
         break;
      case 4:
         flagimage[i] = (game_pens[GROUNDSHADOWPEN] == NOPEN) ?
                        gui_pens[TEXTPEN] : game_pens[GROUNDSHADOWPEN];
         break;
      }
   }
}

